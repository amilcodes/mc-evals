"""Writes SUMMARY.md: one row per task with its difficulty stats and verification status."""
import json
from collections import Counter

import lib


def main():
    ts = [json.load(open(p)) for p in sorted(lib.TASKS.glob("*.json"))]
    order = {"repair": 0, "port": 1, "hidden_rule": 2}
    sizes = {"2x2": 0, "3x2": 1, "3x3": 2, "4x4": 3}
    ts.sort(key=lambda t: (order[t["kind"]], sizes.get(t["size"], 9), t["id"]))
    c = Counter((t["kind"], t["size"]) for t in ts)
    lines = ["# Door task set: summary", "", f"{len(ts)} tasks. Generated by `summarize.py` from `tasks/*.json`.", "",
             "| kind | " + " | ".join(sizes) + " | total |", "|---|" + "---|" * (len(sizes) + 1)]
    for k in order:
        row = [c[(k, s)] for s in sizes]
        lines.append(f"| {k} | " + " | ".join(map(str, row)) + f" | {sum(row)} |")
    lines += ["", "| id | physics | start fails | ref passes | ref vol / ticks | max vol | edit budget | single-edit fix | graded / neighbourhood | same-vol port known |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for t in ts:
        d, v, con = t["difficulty"], t.get("verified", {}), t["constraints"]
        sv = d.get("same_volume_port_known", "")
        sef = d["single_edit_fix"]
        sef = "no" if sef is False else ("YES" if sef is True else "none found (partial)")
        lines.append(
            f"| {t['id']} | {lib.phys_tag(t['physics'])}{'' if t['physics_told'] else ' (hidden)'} | "
            f"{'yes' if v and not v.get('start_passes') else ('?' if not v else 'NO')} | "
            f"{'yes' if v.get('reference_passes') else ('?' if not v else 'NO')} | "
            f"{d['reference_volume']} / {d['reference_open_ticks']}+{d['reference_close_ticks']} | {con['max_volume']} | "
            f"{con.get('edit_budget') if con.get('edit_budget') is not None else '-'} | {sef} | "
            f"{d['neighbours_graded']} / {d['neighbourhood_size']} | {'' if sv == '' else ('yes' if sv else 'no')} |")
    (lib.HERE / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
