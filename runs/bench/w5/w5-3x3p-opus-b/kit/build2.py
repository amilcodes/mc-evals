      ((3,-2,1),(2,-2,1)), ((4,-2,1),(3,-2,1)), ((4,-2,0),(4,-2,1)), ((4,-1,0),(4,-2,0)),  # BR
      ((3,-2,0),(4,-2,0)), ((2,-2,0),(3,-2,0)),   # BM
