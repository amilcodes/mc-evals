      ((4,5,0),(3,5,0)), ((4,4,0),(4,5,0)), ((4,3,0),(4,4,0)),   # TR/MR
      ((-2,5,1),(-2,5,0)), ((-2,4,1),(-2,5,1)), ((-2,3,1),(-2,4,1)), ((-2,2,1),(-2,3,1)),
      ((-2,1,1),(-2,2,1)), ((-2,0,1),(-2,1,1)), ((-2,-1,1),(-2,0,1)), ((-2,-2,1),(-2,-1,1)),
