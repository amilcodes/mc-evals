FACE = {(1,0,0):"east",(-1,0,0):"west",(0,1,0):"up",(0,-1,0):"down",(0,0,1):"south",(0,0,-1):"north"}
def obs(d, p, w):
    v = tuple(w[i]-p[i] for i in range(3))
    d.set(*p, "observer", facing=FACE[v])
def build():
    d = Design("closed")
    for x in range(3):
        for y in range(3): d.set(x,y,0,"stone")
    for p in [(0,-1,0),(2,-1,0),(2,3,0)]: d.set(*p,"stone")
    for y in range(3):
        d.set(-2,y,0,"sticky_piston",facing="east")
        d.set(4,y,0,"sticky_piston",facing="west")
    d.set(1,-2,0,"sticky_piston",facing="up")
    d.set(-1,3,0,"sticky_piston",facing="east")
    d.set(1,4,0,"sticky_piston",facing="down")
    d.set(1,5,0,"sticky_piston",facing="down")
    # lever
    d.set(4,5,0,"stone"); d.set(4,4,0,"lever",face="ceiling",facing="north")
    # junctions
    d.set(1,4,2,"redstone_wire"); d.set(1,5,2,"glass"); d.set(1,6,2,"redstone_wire")
    chain = [
     ((3,4,0),(4,4,0)), ((2,4,0),(3,4,0)),            # E1
     ((4,4,1),(4,4,0)), ((3,4,1),(4,4,1)), ((3,5,1),(3,4,1)), ((2,5,1),(3,5,1)), ((1,5,1),(2,5,1)),
     ((0,5,1),(1,5,1)), ((-1,5,1),(0,5,1)), ((-1,5,0),(-1,5,1)), ((-1,4,0),(-1,5,0)),  # K
     ((-1,6,0),(-1,5,0)), ((-1,6,1),(-1,6,0)), ((-1,6,2),(-1,6,1)), ((0,6,2),(-1,6,2)), # G1
     ((-1,5,2),(-1,6,2)), ((-1,4,2),(-1,5,2)), ((0,4,2),(-1,4,2)),   # E2
     ((-1,7,2),(-1,6,2)), ((0,7,2),(-1,7,2)), ((1,7,2),(0,7,2)), ((2,7,2),(1,7,2)), ((3,7,2),(2,7,2)),
     ((3,6,2),(3,7,2)), ((2,6,2),(3,6,2)),   # G2
     ((3,5,2),(3,6,2)), ((3,4,2),(3,5,2)), ((2,4,2),(3,4,2)),  # E3
     ((1,4,1),(1,4,2)), ((1,6,1),(1,6,2)),   # taps
     ((4,4,2),(4,4,1)), ((4,3,2),(4,4,2)), ((4,2,2),(4,3,2)), ((4,1,2),(4,2,2)), ((4,0,2),(4,1,2)),
     ((-2,4,2),(-1,4,2)), ((-2,3,2),(-2,4,2)), ((-2,2,2),(-2,3,2)), ((-2,1,2),(-2,2,2)), ((-2,0,2),(-2,1,2)),
     ((-2,-1,2),(-2,0,2)), ((-2,-2,2),(-2,-1,2)), ((-1,-2,2),(-2,-2,2)), ((0,-2,2),(-1,-2,2)), ((1,-2,2),(0,-2,2)),
     ((1,-2,1),(1,-2,2)),
    ] + [((-2,y,1),(-2,y,2)) for y in range(3)] + [((4,y,1),(4,y,2)) for y in range(3)]
    for p,w in chain: obs(d,p,w)
    return d
